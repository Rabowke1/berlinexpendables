export const GLYPH_W = 5, GLYPH_H = 7, ADVANCE = 6;
const ORDER = Object.keys(G);

export function normalize(s: string): string {
  return s.toUpperCase().replace(/Ä/g, 'AE').replace(/Ö/g, 'OE').replace(/Ü/g, 'UE').replace(/ß/g, 'SS');
}
export function textWidth(s: string): number { return normalize(s).length * ADVANCE - 1; }

export class Font {
  private cache = new Map<string, HTMLCanvasElement>();
  private sheet(color: string): HTMLCanvasElement {
    let c = this.cache.get(color);
    if (c) return c;
    c = document.createElement('canvas');
    c.width = ORDER.length * GLYPH_W; c.height = GLYPH_H;
    const ctx = c.getContext('2d')!;
    ctx.fillStyle = color;
    ORDER.forEach((ch, i) => G[ch].forEach((row, y) => [...row].forEach((px, x) => { if (px === '#') ctx.fillRect(i * GLYPH_W + x, y, 1, 1); })));
    this.cache.set(color, c);
    return c;
  }
  draw(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, align: 'left' | 'center' | 'right' = 'left', scale = 1): void {
    const s = normalize(text);
    const w = (s.length * ADVANCE - 1) * scale;
    let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
    const sheet = this.sheet(color);
    for (const ch of s) {
      const i = ORDER.indexOf(G[ch] ? ch : '?');
      ctx.drawImage(sheet, i * GLYPH_W, 0, GLYPH_W, GLYPH_H, cx, Math.round(y), GLYPH_W * scale, GLYPH_H * scale);
      cx += ADVANCE * scale;
    }
  }
}
